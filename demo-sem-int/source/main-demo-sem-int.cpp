#include <demo-sem-int-bin.h>
#include "FreeRTOS.h"
#include "task.h"

#include <stdio.h>
#include <functional>
#include <algorithm>
#include "board.h"
#include "peripherals.h"
#include "pin_mux.h"
#include "clock_config.h"
#include "fsl_debug_console.h"

#include "mcxn-kit.h"

// **************************************************************************
//! System initialization. Do not modify it!!!
void _mcu_initialization() __attribute__(( constructor( 0x100 ) ));

void _mcu_initialization()
{
    BOARD_InitBootPins();
    BOARD_InitBootClocks();
    BOARD_InitBootPeripherals();
    BOARD_InitDebugConsole();
    CLOCK_EnableClock( kCLOCK_Gpio0 );
    CLOCK_EnableClock( kCLOCK_Gpio1 );
    CLOCK_EnableClock( kCLOCK_Gpio2 );
    CLOCK_EnableClock( kCLOCK_Gpio3 );
    CLOCK_EnableClock( kCLOCK_Gpio4 );
}

// Start application
int main(void)
{
    PRINTF( "FreeRTOS demo program uses interrupts (ISR) and semaphores.\r\n" );
    PRINTF( "GPIO interrupts are enabled.\r\n" );
    PRINTF( "Interrupts are generated by buttons, see 'gpio_interrupts.cpp' file in 'sem_int' project.\r\n" );
    PRINTF( "Pressing the right button will move red LED to right.\r\n" );
    PRINTF( "Pressing the left button will move red LED to left side.\r\n" );

    // Initialize demo application
    InitDemoApp();

    vTaskStartScheduler();

    while ( 1 );

    return 0 ;
}
